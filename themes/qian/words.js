const DIGITS = '零一二三四五六七八九';

/* 17 → 十七，40 → 四十，100 → 一百 */
export function cn(n) {
  if (n >= 100) return '一百';
  if (n < 10) return DIGITS[n];
  const t = Math.floor(n / 10), o = n % 10;
  return (t === 1 ? '' : DIGITS[t]) + '十' + (o ? DIGITS[o] : '');
}

/* 吉凶：全是好签，只是好的程度不一样 */
const LUCK = [
  ['上上', 12],
  ['上吉', 22],
  ['中吉', 30],
  ['小吉', 22],
  ['中平', 14]
];

function weighted(list) {
  let r = Math.random() * list.reduce((s, x) => s + x[1], 0);
  for (const [v, w] of list) {
    r -= w;
    if (r < 0) return v;
  }
  return list[0][0];
}

/* 抽一支签：签号 1–100，同一轮里不重号 */
export function omen(usedNos = []) {
  let no;
  do no = 1 + Math.floor(Math.random() * 100);
  while (usedNos.includes(no));
  return { no, luck: weighted(LUCK) };
}

