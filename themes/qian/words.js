/* 给一个分类配一首签诗；换一件时尽量换一首不一样的 */
export function poemFor(cat, avoid) {
  const pool = POEMS[cat] || COMMON;
  const others = pool.filter(p => p !== avoid);
  const list = others.length ? others : pool;
  return list[Math.floor(Math.random() * list.length)];
}
